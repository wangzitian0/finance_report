import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { renderHook, waitFor } from "@testing-library/react";
import type { ReactNode } from "react";
import { beforeEach, expect, it, vi } from "vitest";
import { useApiQuery } from "@/hooks/useApiQuery";
import { apiOperation } from "@/lib/api";
vi.mock("@/lib/api", () => ({ apiOperation: vi.fn() }));
const api = vi.mocked(apiOperation), op = "list_accounts_accounts_get" as const, E = expect;
beforeEach(() => api.mockReset());
it("AC-testing.fe-async.1 useApiQuery", async () => {
api.mockResolvedValueOnce({ items: [], total: 0 });
const q1 = renderHook(() => useApiQuery(["ex"], op, {}));
await waitFor(() => E(q1.result.current.isSuccess).toBe(true));
E(q1.result.current.data).toEqual({ items: [], total: 0 });
E(api).toHaveBeenCalledWith(op, {});
api.mockRejectedValueOnce(new Error("500"));
const q2 = renderHook(() => useApiQuery(["fail"], op, {}));
await waitFor(() => E(q2.result.current.isError).toBe(true));
E([q2.result.current.error?.message, q2.result.current.data]).toEqual(["500", undefined]);
const q3 = renderHook(() => useApiQuery(["dis"], op, {}, { enabled: false }));
await waitFor(() => E(q3.result.current.fetchStatus).toBe("idle"));
E([q3.result.current.isPending, api.mock.calls.length]).toEqual([true, 2]);
api.mockResolvedValueOnce({ items: [], total: 3 });
const q4 = renderHook(() => useApiQuery(["sel"], op, {}, { select: (d) => d.total }));
await waitFor(() => E(q4.result.current.isSuccess).toBe(true));
E(q4.result.current.data).toBe(3);
api.mockReset();
api.mockResolvedValue({ items: [], total: 42 });
const qc = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: 60_000 } } }), wrapper = ({ children }: { children: ReactNode }) => <QueryClientProvider client={qc}>{children}</QueryClientProvider>;
const a = renderHook(() => useApiQuery(["s", "k"], op, {}), { wrapper });
await waitFor(() => E(a.result.current.isSuccess).toBe(true));
const b = renderHook(() => useApiQuery(["s", "k"], op, {}), { wrapper });
await waitFor(() => E(b.result.current.isSuccess).toBe(true));
E([b.result.current.data, api.mock.calls.length]).toEqual([{ items: [], total: 42 }, 1]);
const c = renderHook(() => useApiQuery(["s", "o"], op, {}), { wrapper });
await waitFor(() => E(c.result.current.isSuccess).toBe(true));
E(api).toHaveBeenCalledTimes(2);
});
