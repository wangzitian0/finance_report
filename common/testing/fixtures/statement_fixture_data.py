"""Deterministic static test fixture data for banking statement parsing."""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal


@dataclass(frozen=True)
class Transaction:
    date: str
    description: str
    amount: Decimal
    direction: str
    reference: str | None
    suggested_category: str
    category_confidence: Decimal


@dataclass(frozen=True)
class StatementFixture:
    institution: str
    pdf_name: str
    json_name: str
    header: str
    account_masked: str
    account_last4: str
    currency: str
    period_start: str
    period_end: str
    opening_balance: Decimal
    confidence_score: int
    transactions: tuple[Transaction, ...]


def _tx(
    dt: str, desc: str, amt: str, direction: str, cat: str, conf: str
) -> Transaction:
    return Transaction(dt, desc, Decimal(amt), direction, None, cat, Decimal(conf))


def _sf(
    institution: str,
    stem: str,
    header: str,
    masked: str,
    last4: str,
    currency: str,
    start: str,
    end: str,
    opening: str,
    score: int,
    rows: tuple[tuple[str, str, str, str, str, str], ...],
) -> StatementFixture:
    return StatementFixture(
        institution=institution,
        pdf_name=f"{stem}.pdf",
        json_name=f"{stem}_expected.json",
        header=header,
        account_masked=masked,
        account_last4=last4,
        currency=currency,
        period_start=start,
        period_end=end,
        opening_balance=Decimal(opening),
        confidence_score=score,
        transactions=tuple(_tx(*r) for r in rows),
    )


