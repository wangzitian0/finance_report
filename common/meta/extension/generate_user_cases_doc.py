"""Generate ``docs/reference/user-cases.md`` from ``user_cases_ssot.json``.

Single source of truth: ``common/meta/flows/user_cases_ssot.json``.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.meta.base.user_case_proof import (  # noqa: E402
    PROOF_TIER_ORDER,
    ProofTier,
    derive_proof_tier,
    format_proof_tier_cell,
    summarize_domain_tiers,
    summarize_registry_totals,
)

REGISTRY_PATH = REPO_ROOT / "common" / "meta" / "flows" / "user_cases_ssot.json"
OUTPUT_PATH = REPO_ROOT / "docs" / "reference" / "user-cases.md"

_DOMAIN_SUMMARIES: dict[int, str] = {
    1: "Governs tenant registration, session isolation, base reporting currency, environment AI model roles, chart of accounts, and opening balances.",
    2: "Focuses on multi-source ingestion (PDF statements, CSV, multi-currency balances, idempotency, hint-guided re-runs, and workflow status tracking).",
    3: "Governs Stage-1 fact validation, mismatch defense, deduplication, rejection triage, inline AI feedback, auto-accept, and correction replay.",
    4: "Governs Stage-2 economic intent allocation, on-the-fly counter accounts, batch rule commits, payroll gross-to-net splits, and mortgage amortization.",
    5: "Governs internal transfer pairing, cross-period in-transit clearing, credit card repayment, multi-currency FX decomposition, and penny rounding write-off.",
    6: "Governs brokerage holdings, equity trade lot accounting, dividend tax withholding, market prices, physical receipts, alternative assets, asset allocation, and TWR/XIRR performance.",
    7: "Governs balance sheet equation validation, out-of-balance triage, income statement aggregation, cash flow reconciliation, source drilldown, frozen report packages, and annual tax exports.",
    8: "Governs recurring subscription tracking, anomaly detection, and read-only natural language financial advisory.",
}


def render_user_cases_doc(registry: dict[str, Any]) -> str:
    """Render the Markdown 47-User-Case reference and derived coverage matrix."""
    version = registry.get("version", "2.0.0")
    domains = registry.get("domains", [])
    domain_rows = summarize_domain_tiers(domains)
    totals = summarize_registry_totals(domains)

    lines: list[str] = [
        "# 47 Core Business User Cases SSOT",
        "",
        f"> **Version**: `{version}`  ",
        "> **Generated by**: `python -m common.meta.extension.generate_user_cases_doc` (do not edit by hand)  ",
        "> **Source Registry**: [`common/meta/flows/user_cases_ssot.json`](../../common/meta/flows/user_cases_ssot.json)  ",
        "> **Proof-Tier Classifier**: [`common/meta/base/user_case_proof.py`](../../common/meta/base/user_case_proof.py)  ",
        "> **Compliance Test Suites**:",
        "> - Cross-layer contracts: [`tests/tooling/test_user_cases_consistency.py`](../../tests/tooling/test_user_cases_consistency.py)",
        "> - Backend domain invariants: [`apps/backend/tests/flows/test_user_cases_consistency.py`](../../apps/backend/tests/flows/test_user_cases_consistency.py)",
        "",
        "---",
        "",
        "## 1. Overview & Accounting Invariants",
        "",
        "Finance Report governs end-to-end wealth and accounting behavior through **47 canonical User Cases (`UC-01`–`UC-47`)** organized into **8 domains**, preserving all 30 legacy wealth flows 1:1 alongside onboarding, configuration, lot accounting, allocation, performance, and frozen-package lifecycle cases:",
        "",
        "1. **Balance Chain Invariance**: Opening balance + inflows - outflows must exactly match closing balance without silent truncation.",
        "2. **Double-Entry Equilibrium**: Total debits must equal total credits for every posted journal transaction (`sum(Debit) == sum(Credit)`).",
        "3. **No Unposted State Drift**: Reporting surfaces and financial statements only present posted transactions, while out-of-balance conditions trigger explicit diagnostic triage.",
        "4. **Audit Provenance & Cryptographic Traceability**: All financial statements drill down to immutable transaction line items and source documents anchored by SHA-256 digests.",
        "",
        "---",
        "",
        "## 2. Derived Proof-Tier Coverage Matrix",
        "",
        "Proof tiers are derived purely from checked-in test and gap references in `user_cases_ssot.json` (no hand-authored `status` field):",
        "",
        "- `L4_FULL`: `backend_test_ref` + `frontend_test_ref` + `benchmark_cases` + `e2e_test_ref` (no `gap_issue`)",
        "- `L3_E2E`: `backend_test_ref` + `frontend_test_ref` + `e2e_test_ref`",
        "- `L3_BENCH`: `backend_test_ref` + `frontend_test_ref` + `benchmark_cases`",
        "- `L2_SURFACE`: `backend_test_ref` + `frontend_test_ref` only (missing both `e2e_test_ref` and `benchmark_cases`)",
        "- `L1_PARTIAL` / `L0_GAP`: active `gap_issue` tracked in GitHub",
        "",
        "Link each open business bug to its user case in `gap_issue` (`#N` or `#N, #M`).",
        "",
        "| Domain | Total | `L4_FULL` | `L3_E2E` | `L3_BENCH` | `L2_SURFACE` | `L1_PARTIAL` | `L0_GAP` |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]

    for row in domain_rows:
        tier_cells = " | ".join(str(row[tier.value]) for tier in PROOF_TIER_ORDER)
        lines.append(
            f"| **D{row['id']}: {row['name']}** | {row['total']} | {tier_cells} |"
        )

    total_cells = " | ".join(f"**{totals[tier.value]}**" for tier in PROOF_TIER_ORDER)
    lines.append(f"| **Total** | **{totals['total']}** | {total_cells} |")

    gaps_or_partial: list[str] = []
    missing_e2e_and_bench: list[str] = []
    missing_e2e_only: list[str] = []
    missing_bench_only: list[str] = []
    for domain in domains:
        for uc in domain.get("user_cases", []):
            tier = derive_proof_tier(uc)
            if tier in {ProofTier.L0_GAP, ProofTier.L1_PARTIAL}:
                gaps_or_partial.append(f"{uc['id']} ({uc.get('gap_issue')})")
            elif tier == ProofTier.L2_SURFACE_CONTRACT:
                missing_e2e_and_bench.append(uc["id"])
            elif tier == ProofTier.L3_BENCH_PROVEN:
                missing_e2e_only.append(uc["id"])
            elif tier == ProofTier.L3_E2E_PROVEN:
                missing_bench_only.append(uc["id"])

    lines.extend(
        [
            "",
            "### Incremental Proof Upgrade Queue",
            "",
            f"- **Open gaps / partial (`L0_GAP` / `L1_PARTIAL`)**: {', '.join(gaps_or_partial) or 'None'}",
            f"- **Surface-only (`L2_SURFACE` — add E2E or benchmark)**: {', '.join(missing_e2e_and_bench) or 'None'}",
            f"- **Bench without E2E (`L3_BENCH` -> `L4_FULL`)**: {', '.join(missing_e2e_only) or 'None'}",
            f"- **E2E without Bench (`L3_E2E` -> `L4_FULL`)**: {', '.join(missing_bench_only) or 'None'}",
            "",
            "---",
            "",
            "## 3. Eight Canonical Domains Breakdown",
            "",
        ]
    )

    for domain in domains:
        domain_id = int(domain["id"])
        domain_name = str(domain["name"])
        cases = domain.get("user_cases", [])
        span = f"{cases[0]['id']}–{cases[-1]['id']}" if cases else "User Cases"
        lines.extend(
            [
                f"### Domain {domain_id}: {domain_name} ({span})",
                "",
            ]
        )
        summary = _DOMAIN_SUMMARIES.get(domain_id)
        if summary:
            lines.extend([summary, ""])
        lines.extend(
            [
                "| UC ID | User Case (EN / 中文) | UI Surface | Frontend Component | Backend Endpoint | Invariant / Accounting Rule | Proof Tier | Test Reference |",
                "|---|---|---|---|---|---|---|---|",
            ]
        )
        for uc in cases:
            test_ref = str(uc["backend_test_ref"])
            tier_cell = format_proof_tier_cell(uc)
            lines.append(
                f"| **{uc['id']}** "
                f"| {uc['name']}<br>*({uc['title']})* "
                f"| `{uc['ui_surface']}` "
                f"| `{uc['component']}` "
                f"| `{uc['backend_endpoint']}` "
                f"| `{uc['invariant']}` "
                f"| `{tier_cell}` "
                f"| [`{test_ref}`](../../{test_ref}) |"
            )
        lines.extend(["", "---", ""])

    lines.extend(
        [
            "## 4. Invariant Verification & Execution",
            "",
            "To continuously guard against regression, the tooling and backend suites verify that every user-case contract matches the codebase:",
            "",
            "```bash",
            "# 1. Cross-layer User Cases consistency suite",
            'apps/backend/.venv/bin/pytest -n0 --no-cov -o addopts="" tests/tooling/test_user_cases_consistency.py -x',
            "",
            "# 2. Backend domain invariants suite",
            'apps/backend/.venv/bin/pytest -n0 --no-cov -o addopts="" apps/backend/tests/flows/test_user_cases_consistency.py -x',
            "",
            "# 3. Verify this doc matches common/meta/flows/user_cases_ssot.json",
            "python -m common.meta.extension.generate_user_cases_doc --check",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--registry",
        type=Path,
        default=REGISTRY_PATH,
        help="Path to user_cases_ssot.json.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT_PATH,
        help="Markdown output path.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the generated output differs from the checked-in file.",
    )
    args = parser.parse_args(argv)

    registry = json.loads(args.registry.read_text(encoding="utf-8"))
    rendered = render_user_cases_doc(registry)
    output = args.output
    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError:
            print(
                f"ERROR: generated user-cases doc missing: {output}",
                file=sys.stderr,
            )
            return 1
        if current != rendered:
            diff = difflib.unified_diff(
                current.splitlines(),
                rendered.splitlines(),
                fromfile=str(output),
                tofile="generated",
                lineterm="",
            )
            print(
                "ERROR: docs/reference/user-cases.md is out of sync with user_cases_ssot.json.",
                file=sys.stderr,
            )
            print("\n".join(diff), file=sys.stderr)
            return 1
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
