"""Generate ``docs/reference/user-cases.md`` from ``user_cases_ssot.json``.

Single source of truth: ``common/meta/flows/user_cases_ssot.json``.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
REGISTRY_PATH = REPO_ROOT / "common" / "meta" / "flows" / "user_cases_ssot.json"
OUTPUT_PATH = REPO_ROOT / "docs" / "reference" / "user-cases.md"

_DOMAIN_SUMMARIES: dict[int, str] = {
    1: "Governs tenant registration, session isolation, base reporting currency, three-tier AI model bindings, chart of accounts, and opening balances.",
    2: "Focuses on multi-source ingestion (PDF statements, CSV, multi-currency balances, idempotency, hint-guided re-runs, and workflow status tracking).",
    3: "Governs Stage-1 fact validation, mismatch defense, deduplication, rejection triage, inline AI feedback, auto-accept, and correction replay.",
    4: "Governs Stage-2 economic intent allocation, on-the-fly counter accounts, batch rule commits, payroll gross-to-net splits, and mortgage amortization.",
    5: "Governs internal transfer pairing, cross-period in-transit clearing, credit card repayment, multi-currency FX decomposition, and penny rounding write-off.",
    6: "Governs brokerage holdings, equity trade lot accounting, dividend tax withholding, market prices, physical receipts, alternative assets, asset allocation, and TWR/XIRR performance.",
    7: "Governs balance sheet equation validation, out-of-balance triage, income statement aggregation, cash flow reconciliation, source drilldown, frozen report packages, and annual tax exports.",
    8: "Governs recurring subscription tracking, anomaly detection, and read-only natural language financial advisory.",
}


def render_user_cases_doc(registry: dict[str, Any]) -> str:
    """Render the Markdown 47-User-Case reference from ``user_cases_ssot.json``."""
    version = registry.get("version", "2.0.0")
    lines: list[str] = [
        "# 47 Core Business User Cases SSOT",
        "",
        f"> **Version**: `{version}`  ",
        "> **Generated by**: `python tools/generate_user_cases_doc.py` (do not edit by hand)  ",
        "> **Source Registry**: [`common/meta/flows/user_cases_ssot.json`](../../common/meta/flows/user_cases_ssot.json)  ",
        "> **Compliance Test Suites**:",
        "> - Backend: [`apps/backend/tests/flows/test_user_cases_consistency.py`](../../apps/backend/tests/flows/test_user_cases_consistency.py)",
        "> - Frontend: [`apps/frontend/src/__tests__/userCasesConsistency.test.tsx`](../../apps/frontend/src/__tests__/userCasesConsistency.test.tsx)",
        "",
        "---",
        "",
        "## 1. Overview & Accounting Invariants",
        "",
        "Finance Report governs end-to-end wealth and accounting behavior through **47 canonical User Cases (`UC-01`–`UC-47`)** organized into **8 domains**, preserving all 30 legacy wealth flows 1:1 alongside onboarding, configuration, lot accounting, allocation, performance, and frozen-package lifecycle cases:",
        "",
        "1. **Balance Chain Invariance**: Opening balance + inflows - outflows must exactly match closing balance without silent truncation.",
        "2. **Double-Entry Equilibrium**: Total debits must equal total credits for every posted journal transaction (`sum(Debit) == sum(Credit)`).",
        "3. **No Unposted State Drift**: Reporting surfaces and financial statements only present posted transactions, while out-of-balance conditions trigger explicit diagnostic triage.",
        "4. **Audit Provenance & Cryptographic Traceability**: All financial statements drill down to immutable transaction line items and source documents anchored by SHA-256 digests.",
        "",
        "---",
        "",
        "## 2. Eight Canonical Domains Breakdown",
        "",
    ]

    for domain in registry.get("domains", []):
        domain_id = int(domain["id"])
        domain_name = str(domain["name"])
        cases = domain.get("user_cases", [])
        span = f"{cases[0]['id']}–{cases[-1]['id']}" if cases else "User Cases"
        lines.extend(
            [
                f"### Domain {domain_id}: {domain_name} ({span})",
                "",
            ]
        )
        summary = _DOMAIN_SUMMARIES.get(domain_id)
        if summary:
            lines.extend([summary, ""])
        lines.extend(
            [
                "| UC ID | User Case (EN / 中文) | UI Surface | Frontend Component | Backend Endpoint | Invariant / Accounting Rule | Status | Test Reference |",
                "|---|---|---|---|---|---|---|---|",
            ]
        )
        for uc in cases:
            test_ref = str(uc["backend_test_ref"])
            status_cell = (
                f"{uc['status']} ({uc['gap_issue']})"
                if uc.get("gap_issue")
                else uc["status"]
            )
            lines.append(
                f"| **{uc['id']}** "
                f"| {uc['name']}<br>*({uc['title']})* "
                f"| `{uc['ui_surface']}` "
                f"| `{uc['component']}` "
                f"| `{uc['backend_endpoint']}` "
                f"| `{uc['invariant']}` "
                f"| `{status_cell}` "
                f"| [`{test_ref}`](../../{test_ref}) |"
            )
        lines.extend(["", "---", ""])

    lines.extend(
        [
            "## 3. Invariant Verification & Execution",
            "",
            "To continuously guard against regression, both backend and frontend suites validate that every user-case contract aligns with the codebase:",
            "",
            "```bash",
            "# 1. Backend User Cases consistency suite",
            'apps/backend/.venv/bin/pytest apps/backend/tests/flows/test_user_cases_consistency.py -o addopts=""',
            "",
            "# 2. Frontend User Cases consistency suite",
            "cd apps/frontend && npx vitest run src/__tests__/userCasesConsistency.test.tsx",
            "",
            "# 3. Router contract-maturity gate",
            "python tools/audit_router_contracts.py --output docs/reference/router-contract-maturity.md",
            "",
            "# 4. Verify this doc matches common/meta/flows/user_cases_ssot.json",
            "python tools/generate_user_cases_doc.py --check",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--registry",
        type=Path,
        default=REGISTRY_PATH,
        help="Path to user_cases_ssot.json.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT_PATH,
        help="Markdown output path.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the generated output differs from the checked-in file.",
    )
    args = parser.parse_args(argv)

    registry = json.loads(args.registry.read_text(encoding="utf-8"))
    rendered = render_user_cases_doc(registry)
    output = args.output
    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError:
            print(
                f"ERROR: generated user-cases doc missing: {output}",
                file=sys.stderr,
            )
            return 1
        if current != rendered:
            diff = difflib.unified_diff(
                current.splitlines(),
                rendered.splitlines(),
                fromfile=str(output),
                tofile="generated",
                lineterm="",
            )
            print(
                "ERROR: docs/reference/user-cases.md is out of sync with user_cases_ssot.json.",
                file=sys.stderr,
            )
            print("\n".join(diff), file=sys.stderr)
            return 1
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
