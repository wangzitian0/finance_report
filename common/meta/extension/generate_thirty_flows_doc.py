"""Generate ``docs/reference/thirty-wealth-flows.md`` from ``thirty_flows_ssot.json``.

Single source of truth: ``common/meta/flows/thirty_flows_ssot.json``.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
REGISTRY_PATH = REPO_ROOT / "common" / "meta" / "flows" / "thirty_flows_ssot.json"
OUTPUT_PATH = REPO_ROOT / "docs" / "reference" / "thirty-wealth-flows.md"

_DOMAIN_SUMMARIES: dict[int, str] = {
    1: "Focuses on multi-source ingestion (PDF statements, CSV, receipts, and appraisal certificates) with OCR extraction and continuity validation.",
    2: "Governs Stage-1 fact validation, mismatch defense, deduplication, rejection triage, and inline AI assistance.",
    3: "Governs Stage-2 economic intent allocation, counter-account creation, batch clearing, and payroll gross-to-net deductions.",
    4: "Governs internal transfer pairing, credit card repayment clearing, multi-currency realized FX decomposition, and penny rounding write-off.",
    5: "Governs brokerage statement positions, dividend tax withholding, market price updates, and mortgage principal amortization.",
    6: "Governs balance sheet equation validation, out-of-balance root cause diagnostic triage, comparative income trends, and cash flow tripartite reconciliation.",
    7: "Governs PDF provenance drilldown, annual tax zip export with SHA-256 manifests, recurring subscription anomaly detection, and read-only AI advisory.",
}


def render_thirty_flows_doc(registry: dict[str, Any]) -> str:
    """Render the Markdown 30-flow reference from ``thirty_flows_ssot.json``."""
    version = registry.get("version", "1.0.0")
    lines: list[str] = [
        "# 30 Core Wealth & Accounting Flows SSOT",
        "",
        f"> **Version**: `{version}`  ",
        "> **Generated by**: `python tools/generate_thirty_flows_doc.py` (do not edit by hand)  ",
        "> **Source Registry**: [`common/meta/flows/thirty_flows_ssot.json`](../../common/meta/flows/thirty_flows_ssot.json)  ",
        "> **Compliance Test Suites**:",
        "> - Backend: [`apps/backend/tests/flows/test_thirty_flows_consistency.py`](../../apps/backend/tests/flows/test_thirty_flows_consistency.py)",
        "> - Frontend: [`apps/frontend/src/__tests__/thirtyFlowsConsistency.test.tsx`](../../apps/frontend/src/__tests__/thirtyFlowsConsistency.test.tsx)",
        "",
        "---",
        "",
        "## 1. Overview & Architectural Principles",
        "",
        "Finance Report governs wealth and accounting integrity through **30 canonical business flows** organized into **7 domain pillars**. Each flow enforces strict invariant guarantees rooted in double-entry bookkeeping, immutability, and deterministic accounting reconciliation:",
        "",
        "1. **Balance Chain Invariance**: Opening balance + inflows - outflows must exactly match closing balance without silent truncation.",
        "2. **Double-Entry Equilibrium**: Total debits must equal total credits for every posted journal transaction (`sum(Debit) == sum(Credit)`).",
        "3. **No Unposted State Drift**: Reporting surfaces and financial statements only present fully verified transactions, while out-of-balance conditions trigger explicit diagnostic triage.",
        "4. **Audit Provenance & Cryptographic Traceability**: All financial statements drill down to immutable transaction line items and source documents anchored by SHA-256 digests.",
        "",
        "## 2. Seven Canonical Domains Breakdown",
        "",
    ]

    for domain in registry.get("domains", []):
        domain_id = int(domain["id"])
        domain_name = str(domain["name"])
        flows = domain.get("flows", [])
        if flows:
            first_id = flows[0]["id"]
            last_id = flows[-1]["id"]
            flow_span = f"Flows {first_id}–{last_id}"
        else:
            flow_span = "Flows"
        lines.extend(
            [
                "---",
                "",
                f"### Domain {domain_id}: {domain_name} ({flow_span})",
                "",
            ]
        )
        summary = _DOMAIN_SUMMARIES.get(domain_id)
        if summary:
            lines.extend([summary, ""])
        lines.extend(
            [
                "| Flow ID | Flow Name (EN / 中文) | UI Surface | Frontend Component | Backend Endpoint | Invariant / Accounting Rule | Test Reference |",
                "|---|---|---|---|---|---|---|",
            ]
        )
        for flow in flows:
            test_ref = str(flow["backend_test_ref"])
            lines.append(
                f"| **{flow['id']}** "
                f"| {flow['name']}<br>*({flow['title']})* "
                f"| `{flow['ui_surface']}` "
                f"| `{flow['component']}` "
                f"| `{flow['backend_endpoint']}` "
                f"| `{flow['invariant']}` "
                f"| [`{test_ref}`](../../{test_ref}) |"
            )
        lines.append("")

    lines.extend(
        [
            "---",
            "",
            "## 3. Invariant Verification & Execution",
            "",
            "To continuously guard against regression, both backend and frontend suites validate that every flow contract aligns with the codebase:",
            "",
            "```bash",
            "# 1. Backend 30-Flow consistency suite",
            'apps/backend/.venv/bin/pytest apps/backend/tests/flows/test_thirty_flows_consistency.py -o addopts=""',
            "",
            "# 2. Frontend 30-Flow consistency suite",
            "cd apps/frontend && npx vitest run src/__tests__/thirtyFlowsConsistency.test.tsx",
            "",
            "# 3. Router contract-maturity gate",
            "python tools/audit_router_contracts.py --output docs/reference/router-contract-maturity.md",
            "",
            "# 4. Verify this doc matches common/meta/flows/thirty_flows_ssot.json",
            "python tools/generate_thirty_flows_doc.py --check",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--registry",
        type=Path,
        default=REGISTRY_PATH,
        help="Path to thirty_flows_ssot.json.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT_PATH,
        help="Markdown output path.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the generated output differs from the checked-in file.",
    )
    args = parser.parse_args(argv)

    registry = json.loads(args.registry.read_text(encoding="utf-8"))
    rendered = render_thirty_flows_doc(registry)
    output = args.output
    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError:
            print(f"ERROR: generated thirty-wealth-flows doc missing: {output}", file=sys.stderr)
            return 1
        if current != rendered:
            diff = difflib.unified_diff(
                current.splitlines(),
                rendered.splitlines(),
                fromfile=str(output),
                tofile="generated",
                lineterm="",
            )
            print("ERROR: docs/reference/thirty-wealth-flows.md is out of sync with thirty_flows_ssot.json.", file=sys.stderr)
            print("\n".join(diff), file=sys.stderr)
            return 1
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
