#!/usr/bin/env python3
"""Generate backend .env.example block, env-reference doc, and required-env manifest."""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from collections.abc import Sequence
from pathlib import Path

from infra2_sdk.manifests import load_hooks_manifest, run_hook_slot

ROOT_DIR = Path(__file__).resolve().parents[2]
BACKEND_DIR = ROOT_DIR / "apps" / "backend"

if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))


def _settings_module():
    import importlib.util

    config_path = BACKEND_DIR / "src" / "config.py"
    spec = importlib.util.spec_from_file_location("_env_reference_config", config_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _settings_model():
    return _settings_module().Settings


ENV_EXAMPLE_PATH = ROOT_DIR / ".env.example"
ENV_REFERENCE_DOC_PATH = ROOT_DIR / "common" / "runtime" / "env-reference.generated.md"
MANIFEST_SOURCE = "apps/backend/src/config.py::Settings"
REQUIRED_ENV_MANIFEST_PATH = (
    ROOT_DIR / "common" / "runtime" / "required-env.generated.json"
)
RUNTIME_HOOKS_MANIFEST_PATH = ROOT_DIR / "runtime-hooks.manifest.json"

BEGIN_MARKER = "# >>> generated by tools/generate_env_reference.py — do not edit (backend, from config.py) >>>"
END_MARKER = "# <<< end generated (backend) <<<"
FRONTEND_HEADER = "# Frontend Configuration"

GROUP_ORDER = [
    "Database",
    "App Settings",
    "AI Provider",
    "S3 / MinIO Storage",
    "Observability",
    "Security",
    "Feature Flags",
    "Deployment metadata",
    "Rate Limiting",
]

ALIAS_CHAIN_EMPTY_NOTE = (
    'Commented on purpose: an empty assignment is a value, not "unset" — it would '
    "shadow the rest of this key's alias chain. Uncomment and fill in exactly one "
    "name from the chain."
)

_ASSIGNED_KEY_RE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=")
_COMMENTED_KEY_RE = re.compile(r"^\s*#\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=")


def _canonical_key(name: str, field) -> str:
    from pydantic import AliasChoices

    alias = field.validation_alias
    if isinstance(alias, str):
        return alias
    if isinstance(alias, AliasChoices):
        return str(alias.choices[0])
    return name.upper()


def _alias_names(field) -> list[str]:
    from pydantic import AliasChoices

    alias = field.validation_alias
    return (
        [str(c) for c in alias.choices[1:]] if isinstance(alias, AliasChoices) else []
    )


def _render_value(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def _shown_value(field) -> str:
    extra = field.json_schema_extra
    if isinstance(extra, dict) and "example" in extra:
        return str(extra["example"])
    return _render_value(field.default)


def collect_backend_fields() -> list[dict]:
    settings_cls = _settings_model()
    fields: list[dict] = []
    for name, field in settings_cls.model_fields.items():
        extra = field.json_schema_extra
        if not isinstance(extra, dict) or "group" not in extra:
            continue
        fields.append(
            {
                "field": name,
                "key": _canonical_key(name, field),
                "default": _render_value(field.default),
                "has_default": not field.is_required(),
                "value": _shown_value(field),
                "description": (field.description or "").strip(),
                "group": str(extra["group"]),
                "vault": bool(extra.get("injected", False)),
                "extra_keys": list(extra.get("extra_keys", [])),
                "aliases": _alias_names(field),
            }
        )
    return fields


def _group_sort_key(group: str) -> tuple[int, str]:
    return (
        (GROUP_ORDER.index(group), "")
        if group in GROUP_ORDER
        else (len(GROUP_ORDER), group)
    )


def render_backend_block(fields: list[dict]) -> str:
    grouped: dict[str, list[dict]] = {}
    for field in fields:
        grouped.setdefault(field["group"], []).append(field)

    lines: list[str] = []
    for group in sorted(grouped, key=_group_sort_key):
        lines.append(f"# === {group} ===")
        for field in sorted(grouped[group], key=lambda f: f["key"]):
            comment = field["description"] or field["key"]
            if field["vault"]:
                comment = f"{comment} [VAULT]"
            lines.append(f"# {comment}")
            if field["aliases"] and not field["value"]:
                lines.extend([f"# {ALIAS_CHAIN_EMPTY_NOTE}", f"# {field['key']}="])
                continue
            lines.append(f"{field['key']}={field['value']}")
            lines.extend(
                f"{extra_key}={field['value']}" for extra_key in field["extra_keys"]
            )
        lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines)


def env_example_documented_keys(text: str) -> set[str]:
    keys: set[str] = set()
    for line in text.splitlines():
        pattern = (
            _COMMENTED_KEY_RE if line.lstrip().startswith("#") else _ASSIGNED_KEY_RE
        )
        if match := pattern.match(line):
            keys.add(match.group(1))
    return keys


def render_env_example(existing: str | None, fields: list[dict]) -> str:
    managed = f"{BEGIN_MARKER}\n{render_backend_block(fields)}\n{END_MARKER}"
    if existing and BEGIN_MARKER in existing and END_MARKER in existing:
        head, _, rest = existing.partition(BEGIN_MARKER)
        _, _, tail = rest.partition(END_MARKER)
        return f"{head}{managed}{tail}"
    if existing:
        lines = existing.splitlines()
        start = next(
            (i for i, line in enumerate(lines) if FRONTEND_HEADER in line), None
        )
        if start is not None:
            while start > 0 and lines[start - 1].lstrip().startswith("#"):
                start -= 1
            if frontend := "\n".join(lines[start:]).strip("\n"):
                return f"{managed}\n\n{frontend}\n"
    return f"{managed}\n"


def render_reference_doc(fields: list[dict]) -> str:
    rows = sorted(fields, key=lambda f: (_group_sort_key(f["group"]), f["key"]))
    lines = [
        "<!-- GENERATED by tools/generate_env_reference.py — do not edit. -->",
        "",
        "# Backend Environment Reference",
        "",
        "Generated from `apps/backend/src/config.py` (`Settings` pydantic metadata).",
        "Run `python tools/generate_env_reference.py` to regenerate.",
        "",
        "Where a field's `.env.example` value intentionally differs from its code "
        "default (local-dev convenience), both are shown.",
        "",
        "| Key | Default | Example | Vault | Group | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for field in rows:
        default, shown = field["default"], field["value"]
        default_cell = f"`{default}`" if default else ""
        example_cell = f"`{shown}`" if shown and shown != default else ""
        vault_cell = "yes" if field["vault"] else ""
        desc = field["description"].replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| `{field['key']}` | {default_cell} | {example_cell} | {vault_cell} | {field['group']} | {desc} |"
        )
        for extra_key in field["extra_keys"]:
            lines.append(
                f"| `{extra_key}` |  |  | {vault_cell} | {field['group']} | Alias of `{field['key']}`. |"
            )
    lines.append("")
    return "\n".join(lines)


def _environment_contract():
    from infra2_sdk.runtime.config_schema import environment_manifest_from_model

    module = _settings_module()
    try:
        return environment_manifest_from_model(
            module.Settings,
            source=MANIFEST_SOURCE,
            overrides=getattr(module, "ENV_SOURCE_CLASSES", {}),
        )
    except ValueError as error:
        raise SystemExit(f"ENV_SOURCE_CLASSES: {error}") from None


def render_required_env_manifest(fields: list[dict]) -> str:
    contract = _environment_contract()
    vault_by_field = {field["field"]: field["vault"] for field in fields}
    entries = []
    for entry in sorted(contract.fields, key=lambda item: item.env):
        if entry.field not in vault_by_field:
            continue
        data = entry.to_dict()
        data["vault"] = vault_by_field[entry.field]
        entries.append(data)
    manifest = {
        "contract_version": contract.contract_version,
        "generated_by": "tools/generate_env_reference.py — do not edit",
        "source": MANIFEST_SOURCE,
        "consumer": (
            "infra2 CI checks secrets.ctmpl against this manifest "
            "(wangzitian0/finance_report#1828 G-injection-drift-gate); infra2 derives the "
            "template, policy and reconciliation from the source classes (#2005)"
        ),
        "fields": entries,
    }
    return json.dumps(manifest, separators=(",", ":"), ensure_ascii=False) + "\n"


def manifest_gate_errors(manifest=None) -> list[str]:
    from infra2_sdk.ci import validate_manifest_offline
    from infra2_sdk.runtime.config_schema import EnvironmentManifest

    if manifest is None:
        raw_json = render_required_env_manifest(collect_backend_fields())
        manifest = EnvironmentManifest.from_dict(json.loads(raw_json))
    elif isinstance(manifest, dict):
        manifest = EnvironmentManifest.from_dict(manifest)
    elif isinstance(manifest, str):
        manifest = EnvironmentManifest.from_dict(json.loads(manifest))
    return validate_manifest_offline(manifest)


def runtime_hooks_gate_errors(
    hooks_manifest_path: Path | None = None,
    fields: list[dict] | None = None,
) -> list[str]:
    if hooks_manifest_path is None:
        path = RUNTIME_HOOKS_MANIFEST_PATH
    elif hooks_manifest_path.is_dir():
        path = hooks_manifest_path / "runtime-hooks.manifest.json"
    else:
        path = hooks_manifest_path
    try:
        hooks = load_hooks_manifest(path)
    except Exception as error:
        return [f"runtime-hooks.manifest.json: {error}"]

    errors: list[str] = []
    if hooks.service != "finance_report/app":
        errors.append(
            f"runtime-hooks.manifest.json: expected service 'finance_report/app', got {hooks.service!r}"
        )
    if not callable(run_hook_slot):
        errors.append("infra2_sdk.manifests.run_hook_slot is not callable")
    for slot_name in ("smoke", "preview_gate", "staging_gate", "scheduled_audit"):
        if slot_name not in hooks.slots:
            errors.append(f"runtime-hooks.manifest.json: missing slot {slot_name!r}")

    backend_fields = fields if fields is not None else collect_backend_fields()
    known_env_keys: set[str] = {"TEST_USER_EMAIL", "TEST_USER_PASSWORD"}
    for field in backend_fields:
        known_env_keys.update([field["key"], *field["aliases"], *field["extra_keys"]])

    for slot_name, slot in hooks.slots.items():
        for env_key in tuple(slot.required_env) + tuple(slot.optional_env):
            if env_key not in known_env_keys:
                errors.append(
                    f"runtime-hooks.manifest.json: slot {slot_name!r} declares unknown env key {env_key!r}"
                )
    return errors


def _diff(label: str, current: str, generated: str) -> str:
    return "".join(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=f"{label} (on disk)",
            tofile=f"{label} (generated)",
        )
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 (with a diff) if on-disk files differ from generated output.",
    )
    args = parser.parse_args(argv)

    fields = collect_backend_fields()
    existing_env = ENV_EXAMPLE_PATH.read_text() if ENV_EXAMPLE_PATH.exists() else None
    new_env = render_env_example(existing_env, fields)
    new_doc = render_reference_doc(fields)
    new_manifest = render_required_env_manifest(fields)

    targets = (
        (ENV_EXAMPLE_PATH, ".env.example", existing_env, new_env),
        (
            ENV_REFERENCE_DOC_PATH,
            ENV_REFERENCE_DOC_PATH.name,
            ENV_REFERENCE_DOC_PATH.read_text()
            if ENV_REFERENCE_DOC_PATH.exists()
            else "",
            new_doc,
        ),
        (
            REQUIRED_ENV_MANIFEST_PATH,
            REQUIRED_ENV_MANIFEST_PATH.name,
            REQUIRED_ENV_MANIFEST_PATH.read_text()
            if REQUIRED_ENV_MANIFEST_PATH.exists()
            else "",
            new_manifest,
        ),
    )

    if args.check:
        drift = False
        for _path, label, current, generated in targets:
            if current != generated:
                drift = True
                print(_diff(label, current or "", generated))
        gate_errors = manifest_gate_errors(new_manifest) + runtime_hooks_gate_errors(
            RUNTIME_HOOKS_MANIFEST_PATH, fields
        )
        for error in gate_errors:
            print(f"manifest gate: {error}")
        if drift or gate_errors:
            print(
                "ERROR: generated env files are out of date or violate the manifest contract. "
                "Run: python tools/generate_env_reference.py",
                file=sys.stderr,
            )
            return 1
        print(
            "OK: .env.example, env-reference.generated.md and required-env.generated.json are up to date."
        )
        return 0

    ENV_REFERENCE_DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    for path, _label, _current, generated in targets:
        path.write_text(generated)
        print(f"Wrote {path.relative_to(ROOT_DIR)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
