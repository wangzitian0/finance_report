#!/usr/bin/env python3
"""Environment manifests: the infra2 SDK manifest check and the backend block of .env.example.

The SDK (`infra2_sdk.manifests`) renders and checks the backend manifest from `Settings`,
loads the hand-written frontend manifest, and runs the offline contract and the shared
name checks. This module adds what the SDK does not do: the `.env.example` backend block
and the app-specific rules of `runtime-hooks.manifest.json`.
"""

from __future__ import annotations

import argparse
import difflib
import importlib.util
import re
import sys
from collections.abc import Sequence
from functools import cache
from pathlib import Path
from types import ModuleType

from infra2_sdk import manifests as sdk_manifests
from infra2_sdk.manifests import ManifestSpec, load_hooks_manifest

ROOT_DIR = Path(__file__).resolve().parents[2]
BACKEND_DIR = ROOT_DIR / "apps" / "backend"

ENV_EXAMPLE_PATH = ROOT_DIR / ".env.example"
BACKEND_MANIFEST = "common/runtime/required-env.generated.json"
FRONTEND_MANIFEST = "apps/frontend/required-env.manifest.json"
HAND_WRITTEN = (FRONTEND_MANIFEST,)
MANIFEST_SOURCE = "apps/backend/src/config.py::Settings"
RUNTIME_HOOKS_MANIFEST_PATH = ROOT_DIR / "runtime-hooks.manifest.json"
# App-owned cells that must run at least one check; the platform cells run `smoke`.
REQUIRED_HOOK_CELLS = ("preview.post", "staging.post", "prod.post", "scheduled_audit")
# Names that hook checks read and that no settings model declares.
HOOK_ONLY_ENV_KEYS = frozenset(
    {
        "TEST_USER_EMAIL",
        "TEST_USER_PASSWORD",
        "PROD_SMOKE_EMAIL",
        "PROD_SMOKE_PASSWORD",
        "INFRA2_TOUCHED_FILES",
    }
)

BEGIN_MARKER = "# >>> generated by python -m common.runtime.env_manifests — do not edit (backend, from config.py) >>>"
END_MARKER = "# <<< end generated (backend) <<<"
FRONTEND_HEADER = "# Frontend Configuration"

GROUP_ORDER = [
    "Database",
    "App Settings",
    "AI Provider",
    "S3 Storage",
    "Observability",
    "Security",
    "Feature Flags",
    "Deployment metadata",
    "Rate Limiting",
]

_ASSIGNED_KEY_RE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=")
_COMMENTED_KEY_RE = re.compile(r"^\s*#\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=")


@cache
def settings_module() -> ModuleType:
    """Load `apps/backend/src/config.py` without the backend package on `sys.path`."""
    config_path = BACKEND_DIR / "src" / "config.py"
    spec = importlib.util.spec_from_file_location("_env_manifests_config", config_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def specs() -> tuple[ManifestSpec, ...]:
    module = settings_module()
    return (
        ManifestSpec(
            path=BACKEND_MANIFEST,
            model=module.Settings,
            source=MANIFEST_SOURCE,
            overrides=module.ENV_SOURCE_CLASSES,
        ),
    )


def _render_value(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def collect_backend_fields() -> list[dict]:
    """Return one row for each grouped `Settings` field, with its env name and example value."""
    contract = {f.field: f for f in specs()[0].build().fields}
    fields: list[dict] = []
    for name, field in settings_module().Settings.model_fields.items():
        extra = field.json_schema_extra
        if not isinstance(extra, dict) or "group" not in extra:
            continue
        entry = contract[name]
        fields.append(
            {
                "field": name,
                "key": entry.env,
                "value": str(extra["example"]) if "example" in extra else _render_value(field.default),
                "description": (field.description or "").strip(),
                "group": str(extra["group"]),
                "vault": bool(extra.get("injected", False)),
            }
        )
    return fields


def _group_sort_key(group: str) -> tuple[int, str]:
    return (GROUP_ORDER.index(group), "") if group in GROUP_ORDER else (len(GROUP_ORDER), group)


def render_backend_block(fields: list[dict]) -> str:
    grouped: dict[str, list[dict]] = {}
    for field in fields:
        grouped.setdefault(field["group"], []).append(field)

    lines: list[str] = []
    for group in sorted(grouped, key=_group_sort_key):
        lines.append(f"# === {group} ===")
        for field in sorted(grouped[group], key=lambda f: f["key"]):
            comment = field["description"] or field["key"]
            if field["vault"]:
                comment = f"{comment} [VAULT]"
            lines.append(f"# {comment}")
            lines.append(f"{field['key']}={field['value']}")
        lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines)


def env_example_documented_keys(text: str) -> set[str]:
    keys: set[str] = set()
    for line in text.splitlines():
        pattern = _COMMENTED_KEY_RE if line.lstrip().startswith("#") else _ASSIGNED_KEY_RE
        if match := pattern.match(line):
            keys.add(match.group(1))
    return keys


def render_env_example(existing: str | None, fields: list[dict]) -> str:
    managed = f"{BEGIN_MARKER}\n{render_backend_block(fields)}\n{END_MARKER}"
    if existing and BEGIN_MARKER in existing and END_MARKER in existing:
        head, _, rest = existing.partition(BEGIN_MARKER)
        _, _, tail = rest.partition(END_MARKER)
        return f"{head}{managed}{tail}"
    if existing:
        lines = existing.splitlines()
        start = next((i for i, line in enumerate(lines) if FRONTEND_HEADER in line), None)
        if start is not None:
            while start > 0 and lines[start - 1].lstrip().startswith("#"):
                start -= 1
            if frontend := "\n".join(lines[start:]).strip("\n"):
                return f"{managed}\n\n{frontend}\n"
    return f"{managed}\n"


def runtime_hooks_gate_errors(hooks_manifest_path: Path | None = None) -> list[str]:
    """Return the app-specific problems of `runtime-hooks.manifest.json`."""
    path = hooks_manifest_path or RUNTIME_HOOKS_MANIFEST_PATH
    try:
        hooks = load_hooks_manifest(path)
    except (OSError, ValueError) as error:
        return [f"runtime-hooks.manifest.json: {error}"]

    errors: list[str] = []
    if hooks.service != "finance_report/app":
        errors.append(f"runtime-hooks.manifest.json: expected service 'finance_report/app', got {hooks.service!r}")
    for cell_id in REQUIRED_HOOK_CELLS:
        if not hooks.checks_for_cell(cell_id):
            errors.append(f"runtime-hooks.manifest.json: no check runs in cell {cell_id!r}")

    manifests = sdk_manifests.all_manifests(root=ROOT_DIR, specs=specs(), hand_written=HAND_WRITTEN)
    known = set(HOOK_ONLY_ENV_KEYS)
    for manifest in manifests.values():
        known.update(name for f in manifest.fields for name in (f.env, *f.aliases))
    declared = [
        ("manifest", hooks.required_env, hooks.optional_env),
        *((check.id, check.required_env, check.optional_env) for check in hooks.checks),
    ]
    for owner, required, optional in declared:
        errors.extend(
            f"runtime-hooks.manifest.json: {owner!r} declares unknown env key {key!r}"
            for key in (*required, *optional)
            if key not in known
        )
    return errors


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="Exit 1 if a manifest or .env.example is stale or invalid."
    )
    args = parser.parse_args(argv)

    existing_env = ENV_EXAMPLE_PATH.read_text(encoding="utf-8") if ENV_EXAMPLE_PATH.exists() else None
    new_env = render_env_example(existing_env, collect_backend_fields())

    if not args.check:
        sdk_manifests.main(["--write"], root=ROOT_DIR, specs=specs())
        ENV_EXAMPLE_PATH.write_text(new_env, encoding="utf-8")
        print(f"wrote {ENV_EXAMPLE_PATH.relative_to(ROOT_DIR)}")
        return 0

    failed = sdk_manifests.main(["--check"], root=ROOT_DIR, specs=specs(), hand_written=HAND_WRITTEN) != 0
    if existing_env != new_env:
        failed = True
        print(
            "".join(
                difflib.unified_diff(
                    (existing_env or "").splitlines(keepends=True),
                    new_env.splitlines(keepends=True),
                    fromfile=".env.example (on disk)",
                    tofile=".env.example (generated)",
                )
            )
        )
    for error in runtime_hooks_gate_errors():
        failed = True
        print(f"runtime hooks: {error}")
    if failed:
        print("ERROR: environment manifests are stale or invalid. Run: python -m common.runtime.env_manifests", file=sys.stderr)
        return 1
    print("OK: environment manifests and .env.example are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
